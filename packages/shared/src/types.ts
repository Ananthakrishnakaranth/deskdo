/** Hard cap on active (not done, not deleted) items. Enforced on clients and on the server. */
export const MAX_ACTIVE_ITEMS = 8;
export const MAX_TEXT_LENGTH = 500;

/** A to-do item as stored by the server (the source of truth). */
export interface TodoItem {
  id: string; // UUID, generated by the client that created it (makes creates idempotent)
  text: string;
  done: boolean;
  /** Fractional sort key; lower comes first. */
  position: number;
  /** Server time (ISO 8601) of the last accepted write. Strictly increasing across all writes. */
  updatedAt: string;
  /** Tombstone. Deleted items are kept so that late/offline edits can be recognised and ignored. */
  deleted: boolean;
  lastDeviceId: string;
  /** Server-assigned, globally increasing change number. Used as the pull cursor. */
  seq: number;
}

export type TodoPatch = Partial<Pick<TodoItem, "text" | "done" | "position">>;

interface OpBase {
  /** UUID. The server records every processed opId so replays are no-ops. */
  opId: string;
  itemId: string;
  /** Client wall-clock millis — informational only, never used for conflict resolution. */
  clientTime: number;
}
export interface CreateOp extends OpBase {
  type: "create";
  text: string;
  done: boolean;
  position: number;
}
export interface UpdateOp extends OpBase {
  type: "update";
  patch: TodoPatch;
}
export interface DeleteOp extends OpBase {
  type: "delete";
}
export type Op = CreateOp | UpdateOp | DeleteOp;

export type OpStatus =
  | "applied" // written to the database
  | "duplicate" // opId already processed earlier (outbox replay)
  | "ignored" // item is tombstoned or unknown; the op no longer matters
  | "rejected"; // violates a rule (e.g. 9th active item); client must drop it
export interface OpResult {
  opId: string;
  status: OpStatus;
  reason?: string;
}

export interface PushRequest {
  deviceId: string;
  ops: Op[];
}
export interface PushResponse {
  results: OpResult[];
  /** Current server state of every item touched by the batch. */
  items: TodoItem[];
  cursor: number;
}
export interface PullResponse {
  items: TodoItem[];
  cursor: number;
  /**
   * True when the client's cursor predates purged tombstones: `items` is then the complete current
   * state and the client must replace (not merge) its cache.
   */
  reset?: boolean;
}

/** Messages from server to client over the WebSocket. */
export type ServerMessage =
  | { type: "hello"; cursor: number }
  | { type: "changes"; items: TodoItem[]; cursor: number }
  | { type: "ping" }
  | { type: "error"; message: string };

/** Messages from client to server over the WebSocket. */
export type ClientMessage = { type: "auth"; token: string };

export interface LoginRequest {
  email: string;
  password: string;
  deviceId: string;
  /** "bearer" returns the token in the body (desktop); "cookie" sets an httpOnly cookie (PWA). */
  mode: "bearer" | "cookie";
}
export interface LoginResponse {
  token?: string;
  expiresAt: string;
}
